import { app, safeStorage } from 'electron';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { normalizeApiUrl } from '../backend-url.js';

const settingsPath = () => path.join(app.getPath('userData'), 'pos-connection.enc');

const ensureSecureStorage = () => {
  if (!safeStorage.isEncryptionAvailable()) {
    throw new Error('Secure storage is unavailable on this computer. POS credentials were not saved.');
  }
};

export const readSettings = async () => {
  try {
    const encrypted = await readFile(settingsPath());
    ensureSecureStorage();
    const settings = JSON.parse(safeStorage.decryptString(encrypted));
    if (!settings || typeof settings.apiKey !== 'string' || !settings.apiKey) {
      throw new Error('Saved configuration is incomplete.');
    }
    const apiUrl = normalizeApiUrl(settings.apiUrl);
    if (apiUrl !== settings.apiUrl) {
      const migratedSettings = { ...settings, apiUrl };
      await writeSettings(migratedSettings);
      return migratedSettings;
    }
    return settings;
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw new Error('Saved POS connection settings could not be read. Reconnect this terminal.');
  }
};

export const writeSettings = async (settings) => {
  ensureSecureStorage();
  const apiUrl = normalizeApiUrl(settings?.apiUrl);
  if (typeof settings?.apiKey !== 'string' || !settings.apiKey.startsWith('rms_live_')) {
    throw new Error('Enter a valid branch API key generated by RMS.');
  }
  const encrypted = safeStorage.encryptString(JSON.stringify({ ...settings, apiUrl }));
  await writeFile(settingsPath(), encrypted, { mode: 0o600 });
};

export const clearSettings = async () => {
  const { unlink } = await import('node:fs/promises');
  try {
    await unlink(settingsPath());
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
};
