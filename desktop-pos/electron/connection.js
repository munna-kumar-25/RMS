import { normalizeApiUrl } from './backend-url.js';

export const connectBranch = async ({
  apiUrl: inputUrl,
  apiKey: inputKey,
  getSavedKey,
  saveSettings,
  fetchImpl = fetch,
}) => {
  const connection = await testBranchConnection({
    apiUrl: inputUrl,
    apiKey: inputKey,
    getSavedKey,
    fetchImpl,
  });
  await saveSettings({ apiUrl: connection.apiUrl, apiKey: connection.apiKey });
  return { apiUrl: connection.apiUrl, keyPrefix: connection.keyPrefix };
};

export const testBranchConnection = async ({
  apiUrl: inputUrl,
  apiKey: inputKey,
  getSavedKey,
  fetchImpl = fetch,
}) => {
  if (typeof inputUrl !== 'string' || typeof inputKey !== 'string') {
    throw new Error('Backend URL and a branch API key are required.');
  }

  const apiUrl = normalizeApiUrl(inputUrl.trim());
  const apiKey = inputKey.trim() || await getSavedKey();
  if (!apiKey?.startsWith('rms_live_') || apiKey.length > 200) {
    throw new Error('Enter a valid branch API key generated by RMS.');
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 15000);
  try {
    const response = await fetchImpl(`${apiUrl}/menu/items?limit=1`, {
      method: 'GET',
      headers: { 'x-api-key': apiKey },
      signal: controller.signal,
    });
    let payload;
    try {
      payload = await response.json();
    } catch {
      throw new Error(`Backend returned an invalid response (${response.status}).`);
    }
    if (!response.ok) {
      const message = payload?.error?.message || payload?.message || `Backend request failed (${response.status}).`;
      if (response.status === 401 && /invalid or revoked branch api key/i.test(message)) {
        throw new Error('This branch API key is invalid or revoked. Generate a new key in Admin → Branch → API integration, then paste the newly generated key here. A rotated or revoked key cannot be reused.');
      }
      throw new Error(message);
    }

    return { apiUrl, apiKey, keyPrefix: apiKey.slice(0, 17) };
  } catch (error) {
    if (error.name === 'AbortError') {
      throw new Error('Backend request timed out. Check that the server is running and the URL is correct.');
    }
    if (error instanceof TypeError || error.cause || error.message === 'fetch failed') {
      throw new Error(`Could not connect to the backend at ${apiUrl}. Check that the backend is running and the URL and port are correct.`);
    }
    throw error;
  } finally {
    clearTimeout(timeout);
  }
};
